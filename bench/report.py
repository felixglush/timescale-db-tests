#!/usr/bin/env python3
"""Render results/*.csv from run_ablation.py into results/RESULTS.md."""
from __future__ import annotations

import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

RES = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "results"
QUERIES = ["Q1_client_month", "Q2_client_range", "Q3_clients_month", "Q4_clients_range"]


def read(name):
    with open(RES / name) as f:
        return list(csv.DictReader(f))


def mb(b):
    return f"{int(b) / 1024 / 1024:,.1f}"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---:" if i else "---" for i in range(len(header))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    sizes, build, lat = read("sizes.csv"), read("build.csv"), read("latency_summary.csv")
    meta = json.loads((RES / "run_meta.json").read_text())
    rows_by_scale = {int(b["clients"]): int(b["rows"]) for b in build}
    scales = sorted(rows_by_scale)
    variants = list(dict.fromkeys(s["variant"] for s in sizes))
    md = ["# Results", "",
          f"- {meta['postgres'].split(' on ')[0]}, TimescaleDB {meta['timescaledb']}",
          f"- settings: " + ", ".join(f"{k}={v}" for k, v in sorted(meta["settings"].items())),
          f"- run: {meta['started']} → {meta.get('finished', '?')}; args: `{json.dumps(meta['args'])}`",
          "", "Generated by `bench/report.py` from the CSVs in this folder.", ""]

    # ---- storage
    md += ["## Storage (heap + toast + indexes, MB)", ""]
    by = {(int(s["clients"]), s["variant"]): s for s in sizes}
    hdr = ["variant"] + [f"{c:,} clients ({rows_by_scale[c]:,} rows)" for c in scales]
    rows = []
    for v in variants:
        r = [v]
        for c in scales:
            s, p = by[(c, v)], by[(c, "plain")]
            r.append(f"{mb(s['total_bytes'])} ({int(p['total_bytes']) / int(s['total_bytes']):.1f}x)")
        rows.append(r)
    md += [table(hdr, rows), "", "Ratio in brackets = plain size / variant size.", ""]

    md += [f"### Breakdown at {scales[-1]:,} clients", ""]
    rows = []
    for v in variants:
        s = by[(scales[-1], v)]
        rows.append([v, mb(s["table_bytes"]), mb(s["toast_bytes"]), mb(s["index_bytes"]), mb(s["total_bytes"]),
                     f"{int(s['total_bytes']) / rows_by_scale[scales[-1]]:.1f}", s["chunks"]])
    md += [table(["variant", "heap", "toast", "indexes", "total", "bytes/row", "chunks"], rows), ""]

    # ---- build time
    md += ["## Build time (s)", ""]
    bb = {(int(b["clients"]), b["variant"]): b for b in build}
    rows = []
    for v in variants:
        r = [v]
        for c in scales:
            b = bb[(c, v)]
            r.append(f"{float(b['load_s']):.1f} + {float(b['index_s']):.1f} + {float(b['compress_s']):.1f}")
        rows.append(r)
    md += [table(["variant"] + [f"{c:,} clients" for c in scales], rows), "",
           "load + index/FK (+CLUSTER) + compress.", ""]

    # ---- latency
    L = {(int(r["clients"]), r["variant"], r["query"], r["mode"]): r for r in lat}
    for mode, col, title in [
        ("warm", "exec_p50_ms", "Warm, server execution p50 (ms)"),
        ("warm", "exec_p95_ms", "Warm, server execution p95 (ms)"),
        ("warm", "e2e_p50_ms", "Warm, end-to-end client p50 incl. fetching rows into Python (ms)"),
        ("cold", "exec_p50_ms", "Cold (restart + page cache dropped), server execution p50 (ms)"),
        ("cold", "avg_shared_read", "Cold, avg 8 KB blocks read from disk per query"),
        ("warm", "avg_shared_hit", "Warm, avg 8 KB buffers touched per query"),
    ]:
        if not any(k[3] == mode for k in L):
            continue
        md += [f"## {title}", ""]
        for q in QUERIES:
            rows = []
            for v in variants:
                rows.append([v] + [L[(c, v, q, mode)][col] if (c, v, q, mode) in L else "" for c in scales])
            avg_rows = [L[(c, "plain", q, mode)]["avg_rows"] for c in scales if (c, "plain", q, mode) in L]
            md += [f"**{q}** (avg rows returned: {', '.join(avg_rows)})", "",
                   table(["variant"] + [f"{c:,}" for c in scales], rows), ""]
    (RES / "RESULTS.md").write_text("\n".join(md))
    print(f"wrote {RES / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
